# 卡包：p_<类>_<规格>_<编号> → 中文名
_PACK_KIND = {"arcana": "奥术包", "buffoon": "小丑包", "celestial": "天体包",
              "spectral": "幻灵包", "standard": "标准包"}
_PACK_SIZE = {"normal": "普通", "jumbo": "加大", "mega": "巨型"}


def pack_zh(key: str) -> str:
    m = re.match(r"p_(\w+?)_(normal|jumbo|mega)_\d+$", key)
    if m:
        return f"{_PACK_SIZE[m.group(2)]}{_PACK_KIND.get(m.group(1), m.group(1))}"
    return NAME_ZH.get(key, key)


def card_zh(key: str) -> str:
    """卡牌 key → 中文名（观测台显示统一入口）。"""
    if key in NAME_ZH:
        return NAME_ZH[key]
    if key.startswith("p_"):
        return pack_zh(key)
    return key


