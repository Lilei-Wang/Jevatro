def _pack_desc(key: str) -> str:
    import re as _re
    m = _re.match(r"p_(\w+?)_(normal|jumbo|mega)_\d+$", key)
    if m:
        size = _PACK_SIZE[m.group(2)]
        kind = _PACK_KIND.get(m.group(1), m.group(1))
        d = _PACK_DESC.get(m.group(1), "")
        return d
    return ""


